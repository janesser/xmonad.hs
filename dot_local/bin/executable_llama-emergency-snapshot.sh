#!/usr/bin/env bash
# llama-emergency-snapshot.sh — snapshot / restore the emergency llama.cpp build.
#
# WHY
#   The production llama.cpp build (~/projs/llama.cpp/build_cuda, symlinked from
#   ~/.local/bin/llama + ~/.local/bin/llama-server) is a pinned, cleanly-built
#   0.5.0 at commit 7fe450e19. v0.5.0 carries a known weakness, so before
#   rebuilding/upgrading — or whenever you want a rollback point — this archives
#   the *exact current binaries* to a safespot:
#
#       ~/.local/share/llama-emergency
#
#   That directory is RUNTIME DATA, not a chezmoi dotfile: it lives outside
#   chezmoi and git. Only THIS script is chezmoi-managed (for durability); the
#   snapshots it produces are deliberately not version-controlled.
#
# HOW IT WORKS
#   snapshot  -> tar.gz of <prod bin> -> safespot/snapshots/, with a .meta file
#                plus a jsonl index line (commit, version, sha256, path).
#                Idempotent: a ref+backend already snapshotted is skipped.
#   list      -> print the jsonl index.
#   restore   -> extract a snapshot back to the prod bin (rollback) or --dest.
#
# ENV OVERRIDES: LLAMA_EMERGENCY_ROOT, LLAMA_PROD_SRC, LLAMA_PROD_BIN,
#   LLAMA_BACKEND.
#
# Dev tool, NOT a chezmoi run script. `cz apply` renders this executable into
# ~/.local/bin. It never sudo-mounts, never touches systemd or the HF cache,
# and never modifies the live build during a snapshot (the tar is a copy).

set -uo pipefail

LLAMA_EMERGENCY_ROOT="${LLAMA_EMERGENCY_ROOT:-$HOME/.local/share/llama-emergency}"
LLAMA_PROD_SRC="${LLAMA_PROD_SRC:-$HOME/projs/llama.cpp}"
LLAMA_PROD_BIN="${LLAMA_PROD_BIN:-$LLAMA_PROD_SRC/build_cuda/bin}"
LLAMA_BACKEND="${LLAMA_BACKEND:-cuda}"

SNAP_DIR="$LLAMA_EMERGENCY_ROOT/snapshots"
META_DIR="$LLAMA_EMERGENCY_ROOT/meta"
LOG_DIR="$LLAMA_EMERGENCY_ROOT/log"
INDEX="$SNAP_DIR/index.jsonl"
LOG="$LOG_DIR/snapshot.log"

ts()   { date +%H:%M:%S; }
log()  { echo "$(ts) [snap] $*" | tee -a "$LOG"; }
err()  { echo "$(ts) [snap] ERROR: $*" >&2; }

usage() {
  sed -n '2,45p' "$0" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

# ---- command dispatch -------------------------------------------------------
cmd="${1:-snapshot}"
case "$cmd" in
  -h|--help|help)  usage 0 ;;
  snapshot)        shift ;;
  list)            shift ;;
  restore)         shift ;;
  *) err "unknown command: $cmd"; usage 1 ;;
esac

# ---- snapshot ---------------------------------------------------------------
do_snapshot() {
  [ -d "$LLAMA_PROD_SRC/.git" ] || { err "not a git repo: $LLAMA_PROD_SRC"; exit 1; }
  [ -x "$LLAMA_PROD_BIN/llama" ] || { err "prod llama binary missing: $LLAMA_PROD_BIN/llama"; exit 1; }

  local commit short version stamp dest sha
  commit="$(git -C "$LLAMA_PROD_SRC" rev-parse HEAD)"
  short="$(git -C "$LLAMA_PROD_SRC" rev-parse --short HEAD)"
  version="$( "$LLAMA_PROD_BIN/llama" --version 2>/dev/null | sed -n 's/^version: //p' | awk '{print $1}' )"
  stamp="$(date +%Y%m%dT%H%M%S)"
  dest="$SNAP_DIR/llama-${LLAMA_BACKEND}-${short}-${stamp}.tar.gz"

  # Idempotency: same ref + backend already snapshotted -> skip, don't duplicate.
  if [ -s "$INDEX" ] && grep -qF "\"ref\":\"$short\"" "$INDEX"; then
    log "snapshot for ref $short ($LLAMA_BACKEND) already exists — skipping."
    grep -F "$short" "$INDEX" | sed 's/^/  /'
    exit 0
  fi

  mkdir -p "$SNAP_DIR" "$META_DIR" "$LOG_DIR"

  # Archive the prod bin with RELATIVE paths (portable restore) + sorted for
  # reproducible archives. Symlinks preserved as-is.
  log "archiving $LLAMA_PROD_BIN -> $dest"
  ( cd "$LLAMA_PROD_BIN" && tar --sort=name -czf "$dest" . ) \
    || { err "tar failed"; exit 1; }
  sha="$(sha256sum "$dest" | cut -d' ' -f1)"

  cat > "$META_DIR/llama-${LLAMA_BACKEND}-${short}.meta" <<EOF
# llama.cpp emergency build snapshot — generated by llama-emergency-snapshot.sh
ref=$short
commit=$commit
version=$version
backend=$LLAMA_BACKEND
arch=$(uname -m)
host=$(hostname)
build_path=$LLAMA_PROD_BIN
build_mtime=$(date -u -r "$LLAMA_PROD_BIN/llama" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || echo unknown)
tar=$dest
sha256=$sha
snapshot_created=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF

  printf '{"ts":"%s","ref":"%s","version":"%s","backend":"%s","arch":"%s","host":"%s","build_path":"%s","tar":"%s","sha256":"%s"}\n' \
    "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$short" "$version" "$LLAMA_BACKEND" "$(uname -m)" "$(hostname)" \
    "$LLAMA_PROD_BIN" "$dest" "$sha" >> "$INDEX"

  log "snapshot saved: $dest"
  log "meta: $META_DIR/llama-${LLAMA_BACKEND}-${short}.meta"
  log "restore with: $0 restore ${short}"
}

# ---- list -------------------------------------------------------------------
do_list() {
  if [ -s "$INDEX" ]; then
    cat "$INDEX"
  else
    log "no snapshots yet in $INDEX"
  fi
}

# ---- restore ----------------------------------------------------------------
do_restore() {
  local name="" dest="$LLAMA_PROD_BIN" yes=0 src
  while [ $# -gt 0 ]; do
    case "$1" in
      --dest) dest="$2"; shift 2 ;;
      --yes|-y) yes=1; shift ;;
      *) if [ -z "$name" ]; then name="$1"; else err "unexpected arg: $1"; exit 1; fi; shift ;;
    esac
  done

  if [ -z "$name" ]; then
    err "usage: $0 restore <ref-or-snapshot> [--dest DIR] [--yes]"
    exit 1
  fi

  # Resolve ref -> tar (exact filename wins, else glob the shortest ref match).
  if [ -f "$name" ]; then
    src="$name"
  else
    src="$(ls -1 "$SNAP_DIR"/llama-${LLAMA_BACKEND}-${name}-*.tar.gz 2>/dev/null | tail -1)"
  fi
  [ -n "$src" ] && [ -f "$src" ] || { err "snapshot not found for '$name' (backend $LLAMA_BACKEND). Try: $0 list"; exit 1; }

  # Guard: restoring over the LIVE prod bin needs an explicit --yes.
  if [ "$dest" = "$LLAMA_PROD_BIN" ] && [ "$yes" -ne 1 ]; then
    err "restore target is the LIVE prod bin ($dest). Re-run with --yes to confirm."
    exit 1
  fi

  log "restoring $src -> $dest"
  mkdir -p "$dest"
  ( cd "$dest" && tar -xzf "$src" ) || { err "extract failed"; exit 1; }
  log "restore complete: $dest"
}

# ---- run --------------------------------------------------------------------
mkdir -p "$LOG_DIR"
case "$cmd" in
  snapshot) do_snapshot "$@" ;;
  list)     do_list "$@" ;;
  restore)  do_restore "$@" ;;
esac
